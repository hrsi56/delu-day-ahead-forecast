"""Independent metadata-only review: no fits, replay, scores or snapshot writes."""
from pathlib import Path
import hashlib
import json
import os
import subprocess
import sys

ROOT = Path('/Users/djourno/Downloads/PJM/.local/worktrees/cp-26/repair-review-68d5db5')
OUT = Path('/Users/djourno/Downloads/PJM/.local/artifacts/cp-26/repair-v21-r14/fresh-critic-metadata.json')
CANDIDATE = '68d5db593e968c8dcff31c35ecccc355799ddd8e'
INITIAL = '5cc3cc083c4340fd8d792eeaf6551a007987a877'
sys.path.insert(0, str(ROOT / 'src'))
from cp26 import harness as H
from cp26 import parity as P
from cp26.budget import Budget, resource_summary

def git(*args):
    return subprocess.check_output(['git', *args], cwd=ROOT, text=True).strip()

def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

assert os.environ.get('CP26_MONITORED_JOB')
H.check_blas()
assert git('rev-parse', 'HEAD') == CANDIDATE
assert git('status', '--porcelain=v1') == ''
detached = subprocess.run(['git', 'symbolic-ref', '-q', 'HEAD'], cwd=ROOT, capture_output=True).returncode == 1
assert detached
pins = H.identities(ROOT)
landed = H.landed_code(ROOT)
parity = P.require_pass(ROOT)
assert len(parity['checks']) == 96
assert parity['scores_computed'] == 0
support_path = ROOT / 'reports/rebaseline/repair-v21-r14/search-support.json'
support = json.loads(support_path.read_text())
assert support['search_count_for_future_pilot_cost'] == 42
assert support['reported_B_reproduced'] and support['first_window_reported_251_46_reproduced']
for name, expected in support['code_sha256'].items():
    assert sha(ROOT / name) == expected, name
for name, expected in support['inputs_sha256'].items():
    assert sha(ROOT / name) == expected, name
inventory_path = ROOT / 'docs/track-b/evidence/cp-26/repair-v21-r14/initial-inventory.json'
inventory = json.loads(inventory_path.read_text())
preserved = {}
for row in inventory['files']:
    if Path(row['path']).is_absolute() or row['path'].startswith('.local/'):
        continue
    path = ROOT / 'docs/track-b/evidence/cp-26/repair-v21-r14/preserved-r13' / row['path']
    if path.is_file():
        actual = sha(path)
        assert actual == row['sha256'], row['path']
        preserved[row['path']] = actual
assert {'capstone_v21.md', 'scripts/cp26_rebaseline.py', 'tests/test_cp26_monitor.py',
        'reports/rebaseline/parity.json'}.issubset(preserved)
historical = {}
for name in ('docs/track-b/evidence/cp-26/issued-brief.md',
             'docs/track-b/evidence/cp-26/cp28-frozen-protocol.md'):
    historical[name] = sha(ROOT / name)
    assert historical[name] == H.git_blob_sha256(ROOT, INITIAL, name)
result = {'candidate_sha': CANDIDATE, 'head_unchanged': True, 'detached': detached,
          'git_status_porcelain': '', 'pins': pins, 'landed_python_files': len(landed),
          'base_commit': H.BASE_COMMIT, 'anchor_commit': H.ANCHOR_COMMIT,
          'parity': {'sha256': sha(ROOT / P.OUT), 'status': parity['status'],
                     'checks': len(parity['checks']), 'settings': parity['settings'],
                     'candidate_at_gate': parity['candidate_sha'],
                     'current_code_and_inputs_validated': True,
                     'scores_computed': parity['scores_computed'], 'new_fits': 0},
          'support': {'sha256': sha(support_path), 'current_code_and_inputs_validated': True,
                      'B_by_route': support['B_by_route'], 'searches': 42,
                      'repeated_support_computation': False},
          'preserved_r13': preserved, 'original_documents': historical,
          'resources_before_metadata_ending': resource_summary(Budget().read()),
          'snapshot_ignored_byproduct': '.pytest_cache generated by exact requested pytest command',
          'metadata_script_sha256': sha(__file__)}
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(json.dumps(result, ensure_ascii=False, sort_keys=True, indent=2) + '\n')
print(json.dumps({'metadata': str(OUT), 'sha256': sha(OUT), 'pins': len(pins),
                  'landed_python_files': len(landed), 'parity_checks': len(parity['checks']),
                  'preserved_files': len(preserved), 'head_unchanged': True, 'status_clean': True}))
