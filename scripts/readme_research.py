#!/usr/bin/env python3
"""Own the README's generated top: the "At a glance" block and the list of generations
(Publication Standard v1 §8; presentation plan §9.4, finding F04).

Two blocks, each between its own markers, are generated from the registry
(`delu_forecast.registry`) and the claim layer (`delu_forecast.research_claims`), so the README
cannot carry a name, status or number the page does not:

* `<!-- glance:start -->` … `<!-- glance:end -->`, directly under the title: what the project is,
  the headline block (identical to the page's), the terms it introduces, and the demo, the
  report, the evidence and -- once verified -- the MLflow experiment.
* `<!-- research:start -->` … `<!-- research:end -->`: the generations, newest first, each under
  its registry name with its dated status, result, limitations and evidence; then the branches
  that were not adopted.

Everything after them is stable hand-written material (v1's engineering record, setup) that
states no current status. `scripts/cp3_readme.py` keeps its own span.

    uv run python scripts/readme_research.py            # rewrite both blocks in README.md
    uv run python scripts/readme_research.py --check    # exit 1 if either block is stale

The generator fails, rather than guessing, if a marker is missing or appears more than once. Its
one-time migration replaces the hand-written top (v1's "30-second read", which now lives under
v1's heading) with the glance markers; that is the only edit it ever makes outside them.
"""

