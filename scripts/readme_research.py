class MarkerError(RuntimeError):
    pass


def md(template_key: str) -> str:
    return RC.render(template_key, "md", surface=RC.README)


def token(template: str, claim: str = "P23") -> str:
    return RC.render_template(claim, template, "md")


def audit_links(checkpoint_code: str, *, source: str | None = None, line: int | None = None) -> str:
    """Audit-grade evidence (standard §7): each "<type>, frozen <date>", at its evidence tag."""
    checkpoint = G.CHECKPOINTS[checkpoint_code]
    tag, date = checkpoint.evidence_tag, G.EVIDENCE_TAGS[checkpoint.evidence_tag][1]
    items = [("Engineering report", checkpoint.report, None), ("Review verdict", checkpoint.verdict, None)]
    if source:
        items.append(("Raw CSV rows", source, line))
    links = [f"[{kind}, frozen {date}]({GITHUB_URL}/blob/{tag}/{path}{f'#L{row}' if row else ''})"
             for kind, path, row in items]
    return "Evidence: " + " · ".join(links)


def mlflow_route(route: str) -> str | None:
    import json

    index = ROOT / "reports" / "presentation" / "mlflow_index.json"
    if not index.is_file():
        return None
    return json.loads(index.read_text()).get("routes", {}).get(route, {}).get("url")


def build_glance(target: str = "md") -> str:
    """The "At a glance" block. `target="html"` renders the same content with its bindings, so the
    publication lint can read the README's reading path exactly as it reads the page's."""
    released = G.released()
    experiment = mlflow_route("experiment")
    html = target == "html"

    def render(key: str) -> str:
        return RC.render(key, target, surface=RC.README)

    def tok(template: str, claim: str = "P23") -> str:
        return RC.render_template(claim, template, target)

    def bold(text: str) -> str:
        return f"<strong>{text}</strong>" if html else f"**{text}**"

    def link(text: str, url: str) -> str:
        return f'<a href="{url}">{text}</a>' if html else f"[{text}]({url})"

    def para(text: str) -> str:
        return f"<p>{text}</p>" if html else text

    terms = [render(key) for key in RC.headline_terms()]
    body = [
        f"<h2>At a glance</h2>" if html else "## At a glance",
        "",
        para(bold("What it is.") + " Probabilistic forecasts of the next day's hourly German–Luxembourg (DE-LU) "
             "day-ahead electricity price, with prediction intervals, and the record of how successive research "
             "models were compared and checked."),
        "",
        para(bold(f"Research, {tok('{g:current.name}')}.") + " " + RC.headline(target)),
        "",
        ("<ul>" + "".join(f"<li>{term}</li>" for term in terms) + "</ul>") if html
        else "\n".join(f"- {term}" for term in terms),
        "",
        para(bold(f"Demo, {tok('{g:released.name}')}:") + " " + link(f"try the {tok('{g:released.version}')} demo", SPACE_URL)
             + ". " + tok("{g:release_rule}", "P22")),
        "",
        para(bold("How the product works:") + " " + render("product.lede") + " "
             + link("Read it in the report", PAGES_URL + "#product") + ": its data, validation, results, failures, "
             "interval reliability and how to run it."),
        "",
        para(bold("Report:") + " " + link("the one-page report", PAGES_URL) + ", with every result, its limits and its evidence."),
        "",
        para(bold("Evidence:") + " each generation below links its engineering report, its review verdict and its "
             "source rows, frozen at its evidence tag."),
    ]
    if experiment:
        body += ["", para(bold("MLflow:") + " " + link("the <code>delu-generations</code> experiment" if html
                                                     else "the `delu-generations` experiment", experiment)
                          + ", mirrored from the committed evidence; the repository is the source of truth.")]
    if html:
        return "\n".join(line for line in body if line)
    return "\n".join([GLANCE_START, GENERATED, "", *body, "", GLANCE_END])


def not_established(keys: tuple[str, ...]) -> list[str]:
    return ["**What this result does not establish:**", "", *[f"- {md(key)}" for key in keys], ""]


def transition_lines(entry: G.Entry) -> list[str]:
    """The adopted transition into this generation (PUBLISH_RULES 1.0 A3), as on the page: what changed, the
    comparator set in advance, the result and, where the comparator is not the predecessor, why no paired
    predecessor comparison exists. Its limits are the section's own list below."""
    item = G.transition_into(entry)
    if item is None:
        return []
    key = f"transition.{item.id}"
    lines = [f"**{md(f'{key}.title')}.**", ""]
    for name, label in (("change", "What changed"), ("comparator", "Comparator"), ("result", "Result"),
                        ("predecessor", "Against the predecessor")):
        if f"{key}.{name}" in RC.BLOCKS_BY_KEY:
            lines.append(f"- **{label}.** {md(f'{key}.{name}')}")
    return lines + [""]


