def branch_section(entry: G.Entry) -> list[str]:
    return [
        f"#### {entry.name}", "",
        f"*{entry.subtitle}.* {G.status_sentence(entry)}", "",
        f"{md(f'branch.{entry.id}.question')} {md(f'branch.{entry.id}.result')} {md(f'branch.{entry.id}.reason')}", "",
        audit_links(entry.checkpoint), "",
    ]


def build_block() -> str:
    lines = [
        START,
        GENERATED,
        "",
        "## Generations, newest first",
        "",
        f"Names and statuses come from the registry. The research results are development evidence after "
        f"selection, on the same historical hours for every policy; the released model's one-shot holdout is a "
        f"separate evidence class. The [report]({PAGES_URL}#chapters) has the charts and the values.",
        "",
    ]
    for entry in G.generations(newest_first=True):
        lines += generation_section(entry)
    # Rejected branches, grouped where they sit in the lineage and headed apart from the adopted transitions (A3).
    groups: dict[str, list[G.Entry]] = {}
    for entry in G.branches():
        node = entry
        while node.kind != "generation":
            node = G.get(node.after)
        groups.setdefault(node.id, []).append(entry)
    for generation in G.generations():
        if generation.id not in groups:
            continue
        later = next((item.successor for item in G.transitions() if item.predecessor.id == generation.id), None)
        span = f"between {generation.version} and {later.version}" if later else f"after {generation.version}"
        lines += [f"### Experiments not adopted {span}", ""]
        for entry in groups[generation.id]:
            lines += branch_section(entry)
    lines += [
        "### Reading the comparison", "",
        *[f"- {md(key)}" for key in RC.comparison_terms()],
        *([""] if RC.comparison_terms() else []),
        RC.target_sentence("md", surface=RC.README), "",
        md("overview.fairness.readme"), "",
        md("comparison.finding") + " " + md("comparison.caveat"), "",
        md("comparison.scale"), "",
        md("overview.f07"), "",
        "### Further reading", "",
        "- The research updates behind each generation: [CP-20](docs/track-b/research-content/cp20-update.md) and "
        "[CP-15 and CP-16](docs/track-b/research-content/cp15-cp16-update.md).",
        "- The landing records: [CP-21](docs/track-b/cp-21-landing-2026-09-30.md), "
        "[CP-20](docs/track-b/cp-20-landing-2026-09-24.md), "
        "[CP-16](docs/track-b/cp-16-landing-2026-09-23.md) and [CP-15](docs/track-b/cp-15-landing.md). CP-3B's "
        "[unmet Integration item](docs/track-b/evidence/cp-3b/item-6-NOT-COMPLETED.md) is disclosed.",
        "- The Owner-managed Hebrew [Q&A record](שאלות%20תשובות.docx) and the "
        "[research memo](docs/track-b/forecasting-research-2026-09-15.md), which is historical motivation, not a "
        "measured result.",
        "",
        END,
    ]
    return "\n".join(lines)


def _span(text: str, start: str, end: str) -> tuple[int, int]:
    starts, ends = text.count(start), text.count(end)
    if starts != 1 or ends != 1:
        raise MarkerError(
            f"README.md must contain each marker exactly once; found {starts} {start!r} and {ends} {end!r}"
        )
    begin, finish = text.index(start), text.index(end) + len(end)
    if finish < begin:
        raise MarkerError(f"{end!r} precedes {start!r}")
    return begin, finish


def migrate(text: str) -> str:
    """Replace the hand-written top (v1's 30-second read, now under v1's heading) with an empty
    glance span directly under the title, once."""
    if GLANCE_START in text or GLANCE_END in text:
        return text
    if not text.startswith(TITLE + "\n") or START not in text:
        raise MarkerError("no glance markers, and no title and research block to migrate from")
    return f"{TITLE}\n\n{GLANCE_START}\n{GLANCE_END}\n\n" + text[text.index(START):]


def apply(text: str) -> str:
    begin, finish = _span(text, GLANCE_START, GLANCE_END)
    text = text[:begin] + build_glance() + text[finish:]
    begin, finish = _span(text, START, END)
    if begin < text.index(GLANCE_END):
        raise MarkerError("the generations block must follow the glance block")
    return text[:begin] + build_block() + text[finish:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if README.md is stale")
    args = parser.parse_args()
    original = README_PATH.read_text()
    updated = apply(migrate(original))
    if args.check:
        if updated != original:
            print("README generated blocks are stale; run scripts/readme_research.py")
            return 1
        print("README generated blocks are current")
        return 0
    README_PATH.write_text(updated)
    print(f"regenerated the glance and generations blocks of {README_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
