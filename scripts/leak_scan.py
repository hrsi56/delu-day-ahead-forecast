#!/usr/bin/env python3
"""Value-free leak scan: block credential leaks where the credential values are not available.

`scripts/secret_guard.py` compares the actual values of the local credentials, so it passes everything
where no value is configured (CI, a fresh clone, a cloud session). This scan needs no value. It runs after
the secret guard in `.githooks/pre-commit`, `commit-msg` and `pre-push`, and as the first CI step:

    pre-commit           every staged blob
    commit-msg <file>    the commit message
    pre-push <remote>    every blob and message in the outgoing commits (the secret guard's set)
    ci <before> <after>  the pushed range, then the tree. An empty or all-zero `before`, or an expression
                         left unexpanded outside GitHub (`${{ ... }}`), scans the tree alone. A shallow
                         clone is completed from `origin` first; a range that stays unreadable fails closed.
    tree                 every file git tracks or would track in the working tree

Rules:

    F1  salted fingerprints, read from `.githooks/credential-fingerprints.json` beside this script. Each entry
        holds a value's length, alphabet, a random salt and sha256(salt || value), and the same for the
        value's first `prefix_len` characters. Every run of the alphabet in the content is hashed window by
        window and compared. The file is generated by the Owner on his Mac with
        `scripts/credential_fingerprints.py write`; no agent generates it. Absent: F1 is skipped with a
        notice and F2 and F3 still run. Malformed: the scan fails closed.
    F2  environment-dump shapes: a Python `os.environ` repr; a `declare -x`, `export` or bare `NAME=value`
        line, or a dict/JSON entry, whose name looks like a credential (`secret_guard.CREDENTIAL_NAME`) and
        whose value is a literal token rather than a reference or placeholder; an ENTSO-E `securityToken=`
        query value that is not a placeholder.
    F3  known token prefixes (GitHub, Hugging Face, AWS, Slack, OpenAI and Anthropic, Google, GitLab, npm,
        PyPI, Stripe, PEM private keys): a cheap backstop, never the only layer.

A finding names the rule or fingerprint entry and the path, never the matched value. F2 and F3 findings in
the exact (path, rule) pairs of `ALLOWLIST` are suppressed, each for a stated reason, and counted; F1 is never
allowlisted. Any error fails closed (exit 1). Standard library only.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import re
import string
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import secret_guard  # noqa: E402  (the credential-name rule and the outgoing set are the guard's own)

ROOT = Path(__file__).resolve().parents[1]
FINGERPRINTS = ROOT / ".githooks" / "credential-fingerprints.json"
SCHEMA = "delu-credential-fingerprints/1"
ENTRY_KEYS = {"name", "length", "alphabet", "salt", "sha256", "prefix_len", "prefix_sha256"}
MIN_BITS = 128
NULL_OID = secret_guard.NULL_OID
CREDENTIAL_NAME = secret_guard.CREDENTIAL_NAME

#: The alphabets a fingerprinted value may use, smallest first. The generator picks the smallest that holds
#: every character of a value; the scanner looks for runs of it.
ALPHABETS: dict[str, str] = {
    "hex-lower": string.digits + "abcdef",
    "hex-upper": string.digits + "ABCDEF",
    "hex-lower-dash": string.digits + "abcdef-",
    "hex-upper-dash": string.digits + "ABCDEF-",
    "hex": string.digits + "abcdefABCDEF",
    "hex-dash": string.digits + "abcdefABCDEF-",
    "alnum": string.digits + string.ascii_letters,
    "word": string.digits + string.ascii_letters + "_",
    "base64url": string.digits + string.ascii_letters + "_-",
    "base64": string.digits + string.ascii_letters + "+/=",
    "unreserved": string.digits + string.ascii_letters + "_-.~",
    "printable": "".join(chr(c) for c in range(0x21, 0x7F)),
}

# ---------------------------------------------------------------------------------------------------------------
# F2: environment-dump shapes. The patterns are written so that their own source text does not match them.
# Every pattern starts with a literal, which `re` searches fast; a leading word boundary is checked by hand.

#: A literal value: no reference ($, backtick), no template or placeholder bracket, no quote or space.
_VALUE = rb"[A-Za-z0-9_\-./+=:~@%]{12,}"
F2_ENVIRON_REPR = re.compile(rb"environb?\(\{b?['\"][A-Za-z_][A-Za-z0-9_]*['\"]: b?['\"]")
F2_ASSIGNMENT = re.compile(
    rb"[ \t+]*(?:declare[ \t]+-[a-zA-Z]*x[a-zA-Z]*[ \t]+|typeset[ \t]+-x[ \t]+|export[ \t]+)?"
    rb"(?P<name>[A-Za-z_][A-Za-z0-9_]*)=(?P<quote>[\"']?)(?P<value>" + _VALUE + rb")")
F2_ENTRY = re.compile(rb"['\"](?P<name>[A-Za-z_][A-Za-z0-9_]*)['\"][ \t]*:[ \t]*b?['\"](?P<value>" + _VALUE
                      + rb")['\"]")
F2_SECURITY_TOKEN = re.compile(rb"securityToken=(?P<value>[A-Za-z0-9-]{12,})")
_PLACEHOLDER = re.compile(rb"(?i)redact|placeholder|example|your|xxxx|\*\*\*|dummy|changeme|<|>")
#: Lower-case words that every name matching `secret_guard.CREDENTIAL_NAME` contains; lines holding none of
#: them cannot carry a credential-named assignment or entry, so the slower F2 patterns run only near them.
_COVERED = r"TOKEN|SECRET|PASSWORD|PASSWD|API_?KEY|ACCESS_KEY|PRIVATE_KEY"
_CREDENTIAL_WORDS = ([re.compile(word) for word in (b"token", b"secret", b"passw", b"apikey", b"api_key",
                                                     b"access_key", b"private_key")]
                     if CREDENTIAL_NAME.pattern == _COVERED and CREDENTIAL_NAME.flags & re.I
                     else [re.compile(CREDENTIAL_NAME.pattern.lower().encode())])  # a changed rule: still exact
_WORD_BYTES = frozenset((string.ascii_letters + string.digits + "_").encode())

# F3: known token prefixes, (pattern, needs a word boundary before it).
F3_PATTERNS: dict[str, list[tuple[re.Pattern[bytes], bool]]] = {
    "F3-github-token": [(re.compile(rb"gh[pousr]_[A-Za-z0-9]{36}"), True),
                        (re.compile(rb"github_pat_[A-Za-z0-9_]{60,}"), True)],
    "F3-huggingface-token": [(re.compile(rb"hf_[A-Za-z0-9]{30,}\b"), True)],
    "F3-aws-access-key": [(re.compile(rb"AKIA[0-9A-Z]{16}\b"), True), (re.compile(rb"ASIA[0-9A-Z]{16}\b"), True)],
    "F3-slack-token": [(re.compile(rb"xox[abposr]-[0-9A-Za-z-]{10,}"), True)],
    "F3-openai-anthropic-key": [(re.compile(rb"sk-(?:ant-|proj-)?[A-Za-z0-9_-]{32,}"), True)],
    "F3-google-api-key": [(re.compile(rb"AIza[0-9A-Za-z_-]{35}"), True)],
    "F3-gitlab-token": [(re.compile(rb"glpat-[0-9A-Za-z_-]{20,}"), True)],
    "F3-npm-token": [(re.compile(rb"npm_[A-Za-z0-9]{36}\b"), True)],
    "F3-pypi-token": [(re.compile(rb"pypi-AgEIcHlwaS5vcmc[A-Za-z0-9_-]{50,}"), True)],
    "F3-stripe-live-key": [(re.compile(rb"sk_live_[0-9A-Za-z]{20,}"), True),
                           (re.compile(rb"rk_live_[0-9A-Za-z]{20,}"), True)],
    "F3-private-key": [(re.compile(b"-" * 5 + rb"BEGIN (?:[A-Z0-9]+ )*PRIVATE KEY" + b"-" * 5), False)],
}

RULES = {
    "F2-environ-repr": "a Python os.environ repr",
    "F2-env-assignment": "a credential-named NAME=value, export or declare -x line with a literal value",
    "F2-credential-entry": "a credential-named dict or JSON entry with a literal value",
    "F2-security-token": "an ENTSO-E securityToken= query value",
    **{rule: f"a known {rule[3:].replace('-', ' ')} prefix" for rule in F3_PATTERNS},
}

#: Exact (path, rule) pairs whose F2/F3 findings are suppressed, each with its reason. Paths, never globs;
#: F1 is never allowlisted. The count is printed on every run that suppresses something.
ALLOWLIST: dict[tuple[str, str], str] = {
    ("docs/track-b/evidence/cp-20/integration-attempt-1/logs/critic-guards.log", "F2-environ-repr"):
        "the recorded credential exposure itself: two KeyError tracebacks holding the revoked DagsHub token, kept "
        "unredacted by Owner decision because the CP-20 verdict binds the SHAs "
        "(docs/track-b/credential-exposure-2026-09-24.md); frozen evidence",
    ("docs/track-b/evidence/cp-26/landing-repair-3/cleanup.json", "F2-credential-entry"):
        "the key secret_hooks_path records the secret guard's core.hooksPath, a local directory path, not a "
        "credential; frozen CP-26 evidence",
    ("tests/cp25/test_guard.py", "F2-credential-entry"):
        "the CP-25 FAKE fixture dict: literal values that each begin 'fake' or 'hf_fake', set with monkeypatch; "
        "no real credential (landed checkpoint code)",
    ("tests/cp25/test_extract_credentials.py", "F2-credential-entry"):
        "the same CP-25 FAKE fixture dict as tests/cp25/test_guard.py; no real credential (landed checkpoint code)",
}


def _is_literal(value: bytes) -> bool:
    """A value that looks like a real token: no placeholder word, and at least two of lower, upper, digit."""
    if _PLACEHOLDER.search(value):
        return False
    classes = sum(bool(re.search(pattern, value)) for pattern in (rb"[a-z]", rb"[A-Z]", rb"[0-9]"))
    return classes >= 2


def _line(content: bytes, offset: int) -> int:
    return content.count(b"\n", 0, offset) + 1


def _credential_named(match: re.Match) -> bool:
    return bool(CREDENTIAL_NAME.search(match.group("name").decode())) and _is_literal(match.group("value"))


def shape_findings(content: bytes) -> list[tuple[str, int]]:
    """(rule, line) for every F2 and F3 match. Never the matched text."""
    hits: dict[tuple[str, int], None] = {}
    for match in F2_ENVIRON_REPR.finditer(content):
        hits[("F2-environ-repr", match.start())] = None
    lowered = content.lower()
    lines_seen: set[int] = set()
    for word in _CREDENTIAL_WORDS:
        start = end = -1
        for occurrence in word.finditer(lowered):
            if not start <= occurrence.start() < end:  # a new line; a long line is located once per word
                start = content.rfind(b"\n", 0, occurrence.start()) + 1
                end = content.find(b"\n", occurrence.end())
                end = len(content) if end < 0 else end
            if start not in lines_seen:
                lines_seen.add(start)
                assignment = F2_ASSIGNMENT.match(content, start, end)
                if assignment and _credential_named(assignment):
                    hits[("F2-env-assignment", start)] = None
            window_start = max(start, occurrence.start() - 256)
            for entry in F2_ENTRY.finditer(content, window_start, min(end, occurrence.end() + 1024)):
                if _credential_named(entry):
                    hits[("F2-credential-entry", entry.start())] = None
    for match in F2_SECURITY_TOKEN.finditer(content):
        if _is_literal(match.group("value")):
            hits[("F2-security-token", match.start())] = None
    for rule, patterns in F3_PATTERNS.items():
        for pattern, boundary in patterns:
            for match in pattern.finditer(content):
                start = match.start()
                if not boundary or start == 0 or content[start - 1] not in _WORD_BYTES:
                    hits[(rule, start)] = None
    return [(rule, _line(content, offset)) for rule, offset in sorted(hits, key=lambda hit: hit[1])]


