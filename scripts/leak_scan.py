# F1: salted fingerprints.

class MalformedFingerprints(ValueError):
    """The fingerprint file exists but cannot be trusted; the scan fails closed."""


def digest(salt_hex: str, data: bytes) -> str:
    """sha256(salt || data), the salt given as hex. The generator and the scanner share this definition."""
    return hashlib.sha256(bytes.fromhex(salt_hex) + data).hexdigest()


def bits(length: int, alphabet: str) -> float:
    """The estimated entropy of a value: length x log2(alphabet size)."""
    return length * math.log2(len(ALPHABETS[alphabet]))


def smallest_alphabet(value: str) -> str | None:
    chars = set(value)
    named = sorted(ALPHABETS, key=lambda name: len(ALPHABETS[name]))
    return next((name for name in named if chars <= set(ALPHABETS[name])), None)


def _run_pattern(alphabet: str, minimum: int) -> re.Pattern[bytes]:
    members = "".join(re.escape(c) for c in ALPHABETS[alphabet])
    return re.compile(b"[" + members.encode() + b"]{%d,}" % minimum)


class Fingerprint:
    def __init__(self, entry: dict) -> None:
        self.name = entry["name"]
        self.length = entry["length"]
        self.prefix_len = entry["prefix_len"]
        salt = bytes.fromhex(entry["salt"])
        self.full = bytes.fromhex(entry["sha256"])
        self.prefix = bytes.fromhex(entry["prefix_sha256"])
        self.base = hashlib.sha256(salt)
        self.runs = _run_pattern(entry["alphabet"], self.prefix_len)
        #: Runs already hashed and found clean. Repositories repeat the same hashes and identifiers often.
        self.clean: set[bytes] = set()

    def _hit(self, window: bytes, target: bytes) -> bool:
        h = self.base.copy()
        h.update(window)
        return h.digest() == target

    def scan(self, content: bytes) -> str | None:
        """'value' or 'prefix' for the strongest match in the content, or None. The value starts with its
        prefix, so every window of `prefix_len` is hashed and a prefix hit is then checked for the whole value."""
        prefix_seen = False
        p, n = self.prefix_len, self.length
        for match in self.runs.finditer(content):
            run = match.group()
            if run in self.clean:
                continue
            hit = False
            for i in range(len(run) - p + 1):
                if self._hit(run[i:i + p], self.prefix):
                    hit = prefix_seen = True
                    if i + n <= len(run) and self._hit(run[i:i + n], self.full):
                        return "value"
            if not hit and len(self.clean) < 2_000_000:
                self.clean.add(run)
        return "prefix" if prefix_seen else None


def _hex(text, size: int | None = None) -> bool:
    return (isinstance(text, str) and re.fullmatch(r"[0-9a-f]+", text) is not None and len(text) % 2 == 0
            and (size is None or len(text) == size))


def validate_entry(entry) -> None:
    if not isinstance(entry, dict) or set(entry) != ENTRY_KEYS:
        raise MalformedFingerprints("an entry does not have exactly the expected fields")
    name, length, prefix_len, alphabet = entry["name"], entry["length"], entry["prefix_len"], entry["alphabet"]
    if not (isinstance(name, str) and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name)):
        raise MalformedFingerprints("an entry has an invalid name")
    if alphabet not in ALPHABETS:
        raise MalformedFingerprints(f"entry {name} names an unknown alphabet")
    if not all(isinstance(v, int) and not isinstance(v, bool) for v in (length, prefix_len)):
        raise MalformedFingerprints(f"entry {name} has a non-integer length")
    if length < secret_guard.MIN_LENGTH or not 6 <= prefix_len <= length:
        raise MalformedFingerprints(f"entry {name} has an invalid length or prefix length")
    if bits(length, alphabet) < MIN_BITS:
        raise MalformedFingerprints(f"entry {name} is below {MIN_BITS} bits of estimated entropy")
    if not (_hex(entry["salt"]) and len(entry["salt"]) >= 32):
        raise MalformedFingerprints(f"entry {name} has an invalid salt")
    if not (_hex(entry["sha256"], 64) and _hex(entry["prefix_sha256"], 64)):
        raise MalformedFingerprints(f"entry {name} has an invalid digest")


def load_fingerprints(path: Path = FINGERPRINTS) -> list[Fingerprint] | None:
    """The fingerprints, or None when the file is absent. Anything else wrong raises MalformedFingerprints."""
    if not path.exists():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise MalformedFingerprints(f"the file cannot be read as JSON ({type(exc).__name__})") from None
    if not isinstance(data, dict) or data.get("schema") != SCHEMA:
        raise MalformedFingerprints(f"the file does not declare schema {SCHEMA}")
    entries = data.get("entries")
    if not isinstance(entries, list) or not entries:
        raise MalformedFingerprints("the file holds no entries")
    for entry in entries:
        validate_entry(entry)
    return [Fingerprint(entry) for entry in entries]


# ---------------------------------------------------------------------------------------------------------------
# What to scan.

class Item:
    """One piece of content to scan: where it is, its repository path (None for a message), and its bytes."""

    def __init__(self, where: str, path: str | None, content: bytes) -> None:
        self.where, self.path, self.content = where, path, content


def _git(*args: str) -> bytes:
    return subprocess.run(["git", *args], capture_output=True, check=True).stdout


def _blobs(pairs: list[tuple[str, str]], label):
    """Stream (oid, path) blobs through one `git cat-file --batch`, yielding Items."""
    if not pairs:
        return
    proc = subprocess.Popen(["git", "cat-file", "--batch"], stdin=subprocess.PIPE, stdout=subprocess.PIPE)
    try:
        for oid, path in pairs:
            proc.stdin.write(f"{oid}\n".encode())
            proc.stdin.flush()
            header = proc.stdout.readline().split()
            if len(header) != 3:
                raise RuntimeError(f"git cat-file could not read the blob for {path}")
            content = proc.stdout.read(int(header[2]))
            proc.stdout.read(1)
            yield Item(label(path), path, content)
    finally:
        proc.stdin.close()
        proc.stdout.close()
        if proc.wait() != 0:
            raise RuntimeError("git cat-file failed")


def staged_items():
    raw = _git("diff", "--cached", "--raw", "-z", "--no-renames", "--no-abbrev")
    pairs = [(oid, path) for oid, path in secret_guard._changed_blobs(raw)]
    yield from _blobs(pairs, lambda path: f"{path} (staged)")


def message_items(path: str):
    yield Item("the commit message", None, Path(path).read_bytes())


def outgoing_commits(remote: str, stdin: str) -> list[str]:
    """The commits a push would send: secret_guard.py's own rule (rev-list <local> --not --remotes=<remote>)."""
    commits: list[str] = []
    for line in stdin.splitlines():
        parts = line.split()
        if len(parts) != 4 or parts[1] == NULL_OID:
            continue
        exclude = [f"--remotes={remote}"] if remote else []
        listed = _git("rev-list", parts[1], "--not", *exclude).decode().split()
        commits += [c for c in listed if c not in commits]
    return commits


def commit_items(commits: list[str]):
    for commit in commits:
        raw = _git("diff-tree", "-r", "-m", "--root", "--no-commit-id", "--raw", "-z", "--no-renames",
                   "--no-abbrev", commit)
        pairs = list(dict.fromkeys(secret_guard._changed_blobs(raw)))
        yield from _blobs(pairs, lambda path, c=commit: f"{path} (commit {c[:10]})")
        yield Item(f"the message of commit {commit[:10]}", None, _git("log", "-1", "--format=%B", commit))


def tree_items():
    """Every file git tracks or would track (tracked, plus untracked files that are not ignored)."""
    top = Path(_git("rev-parse", "--show-toplevel").decode().strip())
    listed = _git("ls-files", "-z", "--cached", "--others", "--exclude-standard").split(b"\0")
    for raw in dict.fromkeys(p for p in listed if p):
        path = raw.decode(errors="replace")  # for display and the allowlist
        full = top / os.fsdecode(raw)  # the exact file, whatever its name's encoding
        if full.is_symlink():
            yield Item(path, path, str(full.readlink()).encode())
        elif full.is_file():
            yield Item(path, path, full.read_bytes())


# ---------------------------------------------------------------------------------------------------------------
# The ci mode's range.

def _absent(value: str | None) -> bool:
    """An argument that names no commit: empty, all zeros, or an expression GitHub did not expand."""
    value = (value or "").strip()
    return not value or set(value) == {"0"} or "${{" in value or value.lower() in {"null", "none"}


def _commit_present(rev: str) -> bool:
    return subprocess.run(["git", "cat-file", "-e", f"{rev}^{{commit}}"], capture_output=True).returncode == 0


def _shallow() -> bool:
    return _git("rev-parse", "--is-shallow-repository").decode().strip() == "true"


def _fetch(*args: str) -> None:
    subprocess.run(["git", "fetch", "--no-tags", "--quiet", "origin", *args], capture_output=True)


def ci_range(before: str, after: str) -> list[str]:
    """The pushed commits, after completing a shallow clone from origin. Raises when the range is unreadable."""
    for rev in (before, after):
        if not re.fullmatch(r"[0-9a-fA-F]{7,64}", rev):
            raise RuntimeError("the ci range is not a pair of commit ids")
    if _shallow():
        _fetch("--unshallow", after)
    if not _commit_present(before):
        _fetch(before)
    if _shallow() or not (_commit_present(before) and _commit_present(after)):
        raise RuntimeError("the pushed range is unreadable (a commit is missing or the clone is still shallow)")
    return _git("rev-list", "--reverse", after, "--not", before).decode().split()


# ---------------------------------------------------------------------------------------------------------------

def scan(items, fingerprints: list[Fingerprint] | None, allowlist=None) -> tuple[list[str], int]:
    """Findings (rule or entry, and where; never a value) and the number suppressed by the allowlist."""
    allowlist = ALLOWLIST if allowlist is None else allowlist
    findings: list[str] = []
    suppressed = 0
    for item in items:
        for fingerprint in fingerprints or []:
            kind = fingerprint.scan(item.content)
            if kind == "value":
                findings.append(f"F1 the value of {fingerprint.name} appears in {item.where}")
            elif kind == "prefix":
                findings.append(f"F1 the first {fingerprint.prefix_len} characters of {fingerprint.name} "
                                f"appear in {item.where}")
        for rule, line in shape_findings(item.content):
            if item.path is not None and (item.path, rule) in allowlist:
                suppressed += 1
                continue
            findings.append(f"{rule} ({RULES[rule]}) in {item.where}, line {line}")
    return list(dict.fromkeys(findings)), suppressed


USAGE = ("usage: leak_scan.py pre-commit | commit-msg <file> | pre-push <remote> [<url>] "
         "| ci <before> <after> | tree")


def main(argv: list[str]) -> int:
    mode = argv[1] if len(argv) > 1 else ""
    try:
        fingerprints = load_fingerprints()
    except MalformedFingerprints as exc:
        print(f"leak-scan: BLOCKED - {FINGERPRINTS.relative_to(ROOT)} is malformed: {exc}. "
              "Regenerate it with scripts/credential_fingerprints.py write (Owner only).", file=sys.stderr)
        return 1
    if fingerprints is None:
        print(f"leak-scan: notice - {FINGERPRINTS.relative_to(ROOT)} is absent; F1 (fingerprints) skipped, "
              "F2 and F3 still run.", file=sys.stderr)
    try:
        if mode == "pre-commit":
            items = staged_items()
        elif mode == "commit-msg" and len(argv) > 2:
            items = message_items(argv[2])
        elif mode == "pre-push":
            commits = outgoing_commits(argv[2] if len(argv) > 2 else "", sys.stdin.read())
            items = commit_items(commits)
        elif mode == "ci":
            before = argv[2] if len(argv) > 2 else ""
            after = argv[3] if len(argv) > 3 else ""
            if _absent(after):
                after = _git("rev-parse", "HEAD").decode().strip()
            if _absent(before):
                print("leak-scan: ci - no usable 'before' commit; scanning the tree.", file=sys.stderr)
                items = tree_items()
            else:
                commits = ci_range(before, after)
                print(f"leak-scan: ci - scanning {len(commits)} pushed commit(s), then the tree.",
                      file=sys.stderr)
                items = (item for source in (commit_items(commits), tree_items()) for item in source)
        elif mode == "tree":
            items = tree_items()
        else:
            print(USAGE, file=sys.stderr)
            return 2
        findings, suppressed = scan(items, fingerprints)
    except Exception as exc:  # fail closed
        print(f"leak-scan: BLOCKED - the scan could not run ({type(exc).__name__}: {exc})", file=sys.stderr)
        return 1
    if suppressed:
        print(f"leak-scan: {suppressed} finding(s) suppressed by the allowlist ({len(ALLOWLIST)} entries, "
              "each with its reason, in scripts/leak_scan.py)", file=sys.stderr)
    for finding in findings:
        print(f"leak-scan: BLOCKED - {finding}", file=sys.stderr)
    if findings:
        print("leak-scan: remove the value or the dump and retry; never bypass this scan "
              "(AGENTS.md § Credentials).", file=sys.stderr)
        return 1
    if mode in ("ci", "tree"):
        print(f"leak-scan: clean (F1 {'on' if fingerprints else 'skipped'}, F2, F3; "
              f"allowlist {len(ALLOWLIST)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
