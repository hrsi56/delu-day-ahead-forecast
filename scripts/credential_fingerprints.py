#!/usr/bin/env python3
"""Write `.githooks/credential-fingerprints.json`, the F1 input of `scripts/leak_scan.py`. Owner only.

    python3 scripts/credential_fingerprints.py write [--only NAME[,NAME...]] [--env-only] [--out PATH]

The values are read inside this process from the same sources as `scripts/secret_guard.py` (the environment,
`launchctl getenv` and the `export` lines of `~/.zshrc`), one per distinct value. Every value must carry at
least 128 bits of estimated entropy (length x log2(alphabet size), over the smallest alphabet of
`leak_scan.ALPHABETS` that holds it); otherwise nothing is written and the weak variable is named. Each entry
holds the value's length and alphabet, a fresh random salt, sha256(salt || value), and the same for the value's
first half (`prefix_len`). Only names are printed, never a value, a length or a digest.

The file is append-only: existing entries are kept, so a rotated (revoked) value stays detectable, and a value
already fingerprinted is not added again. `--only` limits the run to the named variables (as the secret guard
names them).

`--env-only`, or SECRET_GUARD_ENV_ONLY=1 as for the secret guard, restricts the sources to the process
environment. Tests use it with fake values generated at run time. No agent runs `write` against the real
sources, and no agent creates the committed file: the Owner generates it on his Mac.
"""
from __future__ import annotations

import argparse
import json
import os
import secrets
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import leak_scan  # noqa: E402
import secret_guard  # noqa: E402


class Refused(ValueError):
    pass


def entry_for(name: str, value: str) -> dict:
    """One fingerprint entry, or Refused when the value is not ASCII or is below the entropy floor."""
    alphabet = leak_scan.smallest_alphabet(value)
    if alphabet is None:
        raise Refused(f"{name}: the value has characters outside the known alphabets")
    if leak_scan.bits(len(value), alphabet) < leak_scan.MIN_BITS:
        raise Refused(f"{name}: the value is below {leak_scan.MIN_BITS} bits of estimated entropy")
    salt = secrets.token_hex(16)
    prefix_len = len(value) // 2
    entry = {"name": name, "length": len(value), "alphabet": alphabet, "salt": salt,
             "sha256": leak_scan.digest(salt, value.encode()), "prefix_len": prefix_len,
             "prefix_sha256": leak_scan.digest(salt, value[:prefix_len].encode())}
    leak_scan.validate_entry(entry)
    return entry


def _known(entries: list[dict], value: str) -> bool:
    return any(e["length"] == len(value) and leak_scan.digest(e["salt"], value.encode()) == e["sha256"]
               for e in entries)


def write(out: Path, only: set[str] | None) -> int:
    existing: list[dict] = []
    if out.exists():
        try:
            leak_scan.load_fingerprints(out)
        except leak_scan.MalformedFingerprints as exc:
            print(f"credential-fingerprints: REFUSED - {out} is malformed ({exc}); nothing written.",
                  file=sys.stderr)
            return 1
        existing = json.loads(out.read_text(encoding="utf-8"))["entries"]
    found = [(name, value) for name, value in secret_guard.credentials() if only is None or name in only]
    if only:
        missing = sorted(only - {name for name, _ in found})
        if missing:
            print(f"credential-fingerprints: REFUSED - no value found for {', '.join(missing)}; nothing written.",
                  file=sys.stderr)
            return 1
    if not found:
        print("credential-fingerprints: REFUSED - no credential value found; nothing written.", file=sys.stderr)
        return 1
    added, refused, kept_names = [], [], []
    for name, raw in found:
        try:
            value = raw.decode("ascii")
        except UnicodeDecodeError:
            refused.append(f"{name}: the value is not ASCII")
            continue
        if _known(existing, value):
            kept_names.append(name)
            continue
        try:
            added.append(entry_for(name, value))
        except Refused as exc:
            refused.append(str(exc))
    if refused:
        for reason in refused:
            print(f"credential-fingerprints: REFUSED - {reason}", file=sys.stderr)
        print("credential-fingerprints: nothing written. Use --only to choose the variables to fingerprint.",
              file=sys.stderr)
        return 1
    data = {"schema": leak_scan.SCHEMA,
            "about": "Salted SHA-256 fingerprints of the Owner's credential values, read by scripts/leak_scan.py "
                     "(F1). Generated by scripts/credential_fingerprints.py write on the Owner's Mac; append-only; "
                     "never edited by hand.",
            "entries": existing + added}
    out.parent.mkdir(parents=True, exist_ok=True)
    temporary = out.with_name(out.name + ".tmp")
    temporary.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    leak_scan.load_fingerprints(temporary)  # the scanner must accept what was written
    os.replace(temporary, out)
    names = ", ".join(entry["name"] for entry in added) or "none"
    already = f"; already present: {', '.join(kept_names)}" if kept_names else ""
    print(f"credential-fingerprints: wrote {out}: added {len(added)} ({names}); "
          f"{len(existing)} existing entries kept{already}.")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="credential_fingerprints.py", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="mode", required=True)
    w = sub.add_parser("write", help="fingerprint the local credential values (Owner only)")
    w.add_argument("--only", help="comma-separated variable names to fingerprint")
    w.add_argument("--env-only", action="store_true", help="read the process environment only (tests)")
    w.add_argument("--out", type=Path, default=leak_scan.FINGERPRINTS, help="the file to write")
    args = parser.parse_args(argv[1:])
    if args.env_only:
        os.environ["SECRET_GUARD_ENV_ONLY"] = "1"
    only = {name.strip() for name in args.only.split(",") if name.strip()} if args.only else None
    return write(args.out, only)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
